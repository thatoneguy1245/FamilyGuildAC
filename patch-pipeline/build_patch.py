#!/usr/bin/env python3
"""Apply custom/spells.yaml to a local Spell.dbc copy, pack Patch-A.MPQ, emit spell_dbc SQL.

Usage: build_patch.py --spell-dbc /path/to/Spell.dbc [--out build] [--mpqcli mpqcli] [--no-mpq]
The source Spell.dbc is never modified and must never be committed.
"""
import argparse, os, shutil, struct, subprocess, sys, yaml
from wdbc import DBC

HERE = os.path.dirname(os.path.abspath(__file__))
SPELL_FIELDS = 234                       # 3.3.5a (12340) Spell.dbc
F_DIESIDES, F_BASEPTS = 74, 80           # EffectDieSides[3], EffectBasePoints[3]
F_NAME, F_RANK, F_DESC, F_TIP = 136, 153, 170, 187  # enUS slot of each 17-field loc string
MIN_CUSTOM_ID = 90000

def f2s(v):  # render a uint32 for SQL as signed int (spell_dbc uses INT columns)
    return str(struct.unpack("<i", struct.pack("<I", v))[0])

def apply(dbc, spec):
    if dbc.fields != SPELL_FIELDS:
        raise SystemExit(f"Spell.dbc has {dbc.fields} fields, expected {SPELL_FIELDS} (3.3.5a)")
    new = []
    for s in spec["spells"]:
        sid = int(s["id"])
        if sid < MIN_CUSTOM_ID:
            raise SystemExit(f"spell id {sid} below custom range {MIN_CUSTOM_ID}")
        if dbc.find(sid):
            raise SystemExit(f"spell id {sid} already exists in Spell.dbc")
        src = dbc.find(int(s["clone_from"]))
        if src is None:
            raise SystemExit(f"clone_from {s['clone_from']} not found")
        r = list(src); r[0] = sid
        for field, key in ((F_NAME, "name"), (F_RANK, "rank"), (F_DESC, "description"), (F_TIP, "tooltip")):
            if key in s:
                r[field] = dbc.add_string(s[key] or "")
        for e in s.get("effects", []):
            i = int(e["index"])
            if "base_points" in e: r[F_BASEPTS + i] = int(e["base_points"]) & 0xFFFFFFFF
            if "die_sides" in e: r[F_DIESIDES + i] = int(e["die_sides"]) & 0xFFFFFFFF
        dbc.records.append(r); new.append((r, s))
    dbc.records.sort(key=lambda r: r[0])
    return new

def sql_for(new):
    out = ["-- Generated by patch-pipeline/build_patch.py. Do not edit by hand.",
           "-- Positional insert: spell_dbc columns mirror Spell.dbc field order (234 cols)."]
    for r, s in new:
        vals = []
        for i, v in enumerate(r):
            if i in (F_NAME, F_RANK, F_DESC, F_TIP):
                key = {F_NAME: "name", F_RANK: "rank", F_DESC: "description", F_TIP: "tooltip"}[i]
                txt = (s.get(key) or "") if key in s else ""
                vals.append("'" + txt.replace("\\", "\\\\").replace("'", "''") + "'")
            elif F_NAME < i < F_TIP + 17 and (i - F_NAME) % 17 != 16:
                vals.append("''")  # other locale strings
            else:
                vals.append(f2s(v))
        out.append(f"DELETE FROM `spell_dbc` WHERE `ID` = {r[0]};")
        out.append(f"INSERT INTO `spell_dbc` VALUES ({', '.join(vals)});")
    return "\n".join(out) + "\n"

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--spell-dbc", required=True)
    ap.add_argument("--spec", default=os.path.join(HERE, "custom", "spells.yaml"))
    ap.add_argument("--out", default=os.path.join(HERE, "build"))
    ap.add_argument("--sql-out", default=os.path.join(HERE, "..", "sql", "custom", "spell_dbc_flare.sql"))
    ap.add_argument("--mpqcli", default=shutil.which("mpqcli") or os.path.join(HERE, "tools", "mpqcli"))
    ap.add_argument("--no-mpq", action="store_true")
    a = ap.parse_args(argv)
    dbc = DBC.load(a.spell_dbc)
    new = apply(dbc, yaml.safe_load(open(a.spec)))
    stage = os.path.join(a.out, "stage", "DBFilesClient")
    os.makedirs(stage, exist_ok=True)
    dbc.save(os.path.join(stage, "Spell.dbc"))
    os.makedirs(os.path.dirname(a.sql_out), exist_ok=True)
    open(a.sql_out, "w").write(sql_for(new))
    if not a.no_mpq:
        mpq = os.path.join(a.out, "Patch-A.MPQ")
        if os.path.exists(mpq): os.remove(mpq)
        subprocess.run([a.mpqcli, "create", "-g", "wow-wotlk", mpq,
                        os.path.join(a.out, "stage")], check=True)
    print(f"added {len(new)} spell(s); outputs in {a.out}")

if __name__ == "__main__":
    sys.exit(main())
